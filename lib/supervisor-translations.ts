export function getTranslatedSupervisor(text: string, lang: 'es' | 'en'): string {
    if (lang === 'es') return text
    // Strict map lookup first
    if (SUPERVISOR_TRANSLATIONS[text]?.en) return SUPERVISOR_TRANSLATIONS[text].en
    // Normalized fallback: try trimmed version
    const trimmed = text.trim()
    if (trimmed !== text && SUPERVISOR_TRANSLATIONS[trimmed]?.en) return SUPERVISOR_TRANSLATIONS[trimmed].en
    return text
}
