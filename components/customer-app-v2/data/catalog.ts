/**
 * Empareja un artículo del menú vivo de Toast con su contraparte fotográfica oficial
 * cuando no trae `imageUrl` directo o se requiere su lockup visual.
 */
export function matchShowcaseDishForLiveItem(liveName: string): SignatureDish | undefined {
  for (const rule of SHOWCASE_MATCH_KEYWORDS) {
    if (rule.keyword.test(liveName)) {
      return SIGNATURE_DISHES.find((d) => d.id === rule.dishId)
    }
  }
  return undefined
}
